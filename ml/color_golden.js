'use strict';
// Golden data for the phone's colour ranking (BrickCore ColorRanking), computed by the server's own code.
//
//   python3 ml/part_details.py --data data 3001 3023 ... --out /tmp/details.json
//   node ml/color_golden.js --data data --details /tmp/details.json --out ios/BrickCore/Tests/BrickCoreTests/ColorRankingGolden.swift
//
// For every part in the details file and every measured colour below, it records the server's ranking
// (`colorsForPart` in lib/catalog.js) restricted to the colours the details file keeps, which is exactly
// what the phone must produce from that file. It also checks that each kept colour's count equals the
// server's, and reports how often the server's first choice is among the kept colours.
const fs = require('node:fs');
const path = require('node:path');
const { Catalog } = require('../lib/catalog');
const { hexToRgb } = require('../lib/color');

const MEASURED = ['b02a1e', 'e0e0d8', '202428', '8a8f92', 'd8b830', '3a6fb0', 'c0d8ee', '6b4a2f', '4f7a3a', 'f08a30'];

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : fallback;
}

async function main() {
  const dataDir = arg('data', 'data');
  const detailsFile = arg('details');
  const out = arg('out');
  const name = arg('name', 'realCatalog');
  if (!detailsFile) throw new Error('--details is required');
  const bundle = JSON.parse(fs.readFileSync(detailsFile, 'utf8'));
  const catalog = await Catalog.load(dataDir);

  const cases = [];
  let mismatched = 0, topKept = 0, topTotal = 0;
  for (const c of bundle.classes) {
    if (!c.details) continue;
    const p = catalog.resolvePart(c.partNum);
    if (p === undefined) throw new Error(`server does not know ${c.partNum}`);
    const kept = new Set(c.details.colors.map(([id]) => id));
    for (const [id, n] of c.details.colors) {
      const server = catalog.keyUse.get(p * catalog.NC + catalog.colorIdx.get(id)) || 0;
      if (server !== n) { mismatched++; console.error(`${c.partNum} colour ${id}: bundle ${n}, server ${server}`); }
    }
    for (const hex of [null, ...MEASURED]) {
      const ranking = catalog.partInfo(p, hex ? hexToRgb(hex) : null).colors.map((col) => col.id);
      if (hex) { topTotal++; if (kept.has(ranking[0])) topKept++; }
      cases.push({ part: c.partNum, rgb: hex, expected: ranking.filter((id) => kept.has(id)) });
    }
  }
  console.error(`${cases.length} cases; ${mismatched} colour counts differ from the server's; ` +
    `server's first colour kept in the bundle for ${topKept} of ${topTotal} measured colours`);
  if (mismatched) process.exitCode = 1;
  if (!out) return;

  const lines = [
    '// Generated by ml/color_golden.js from the server\'s colorsForPart (lib/catalog.js). Do not edit by hand.',
    `// Catalog: ${path.basename(path.resolve(dataDir))}; details: ml/part_details.py.`,
    '',
    'extension ColorRankingGolden {',
    `    static let ${name}Bundle = #"""`,
    JSON.stringify(bundle),
    '"""#',
    '',
    `    static let ${name}Cases: [Case] = [`,
    ...cases.map((k) => `        Case(part: ${JSON.stringify(k.part)}, rgb: ${k.rgb ? JSON.stringify(k.rgb) : 'nil'}, expected: [${k.expected.join(', ')}]),`),
    '    ]',
    '}',
    '',
  ];
  fs.writeFileSync(out, lines.join('\n'));
  console.error(`wrote ${out}`);
}

main().catch((err) => { console.error(err.message || err); process.exit(1); });
